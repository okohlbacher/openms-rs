//! Evidence tier 1 for `FeatureGroupingAlgorithmWNet`: the algorithm path of
//! the upstream `TOPP_FeatureLinkerWNet_1` test against its retained C++
//! output.
//!
//! Upstream definition: `topp/CMakeLists.txt:2955-2958` at test-data revision
//! 0cb15f2 runs `FeatureLinkerWNet -test -ini FeatureLinkerWNet_1_parameters.ini
//! -in FeatureLinkerUnlabeled_1_input1..3.featureXML` and compares with
//! `FeatureLinkerWNet_1_output.consensusXML` through
//! `${DIFF} -whitelist "id=" "href="`. The retained ini and output were
//! generated by tool version `3.6.0-pre-wnetalign-2026-03-25`, which
//! predates the pinned wnetalign v0.9.8 (April 2026): where the two differ,
//! the executed pin is the oracle (`tests/mapmatching_wnet_grouping_oracle.rs`
//! case `g_wnet1`, same inputs and parameters), and this file shows which.
//!
//! The tool (`FeatureLinkerBase.cpp` at topp revision 174b576) loads every
//! featureXML without convex hulls and subordinates, clears each feature's
//! meta values except `dc_charge_adducts` and `Group`, calls
//! `group(maps, out_map)`, then assigns fresh unique IDs and sorts
//! identifications, which change neither the order nor the values compared.
//!
//! Compared as in `tests/mapmatching_qt_cluster_finder_topp.rs`: order, handle
//! identities exactly, values within the six significant digits stored.

#![cfg(all(feature = "featurexml", feature = "consensusxml", feature = "paramxml"))]

use openms::analysis::mapmatching::feature_grouping_algorithm::FeatureGroupingAlgorithm;
use openms::analysis::mapmatching::feature_grouping_algorithm_wnet::FeatureGroupingAlgorithmWNet;
use openms::format::{consensusxml, featurexml, paramxml};
use openms::kernel::features::{ConsensusMap, FeatureMap};

const DIR: &str = "tests/data";

fn load(file: &str) -> FeatureMap {
    let mut map = featurexml::load(format!("{DIR}/{file}")).unwrap();
    for feature in &mut map.features {
        feature.subordinates.clear();
        feature.convex_hulls.clear();
        let adduct = feature.metadata.get("dc_charge_adducts").cloned();
        let group = feature.metadata.get("Group").cloned();
        feature.metadata.clear();
        if let Some(adduct) = adduct {
            feature.metadata.insert("dc_charge_adducts".into(), adduct);
        }
        if let Some(group) = group {
            feature.metadata.insert("Group".into(), group);
        }
    }
    map
}

fn close(actual: f64, expected: f64, relative: f64, what: &str) {
    let bound = relative * expected.abs() + 1e-6;
    assert!(
        (actual - expected).abs() <= bound,
        "{what}: produced {actual}, retained {expected}"
    );
}

#[test]
fn topp_feature_linker_wnet_1() {
    // The tool hands the ini's `algorithm` section to setParameters.
    let ini = paramxml::load(format!("{DIR}/feature_linker_wnet_1_parameters.ini")).unwrap();
    let section = ini.copy("FeatureLinkerWNet:1:algorithm:", true).unwrap();
    let (mut algorithm, warnings) =
        FeatureGroupingAlgorithmWNet::from_param_with_warnings(&section).unwrap();
    assert!(warnings.is_empty(), "{warnings:?}");
    assert_eq!(algorithm, FeatureGroupingAlgorithmWNet::default());

    let maps: Vec<FeatureMap> = (1..=3)
        .map(|n| load(&format!("feature_linker_unlabeled_1_input{n}.featureXML")))
        .collect();
    let mut out = ConsensusMap::new();
    algorithm.group(&maps, &mut out).unwrap();

    let expected =
        consensusxml::load(format!("{DIR}/feature_linker_wnet_1_output.consensusXML")).unwrap();
    assert_eq!(out.len(), expected.len(), "consensus feature count");
    let float_rel = 5.0e-6 + f64::from(f32::EPSILON);
    for (index, (produced, retained)) in out.features.iter().zip(&expected.features).enumerate() {
        let at = format!("consensus feature {index}");
        let keys: Vec<_> = produced.handles().iter().map(|h| h.key()).collect();
        let retained_keys: Vec<_> = retained.handles().iter().map(|h| h.key()).collect();
        assert_eq!(keys, retained_keys, "{at}: handles");
        close(produced.rt, retained.rt, 5.0e-6, &format!("{at} RT"));
        close(produced.mz, retained.mz, 5.0e-6, &format!("{at} m/z"));
        close(
            f64::from(produced.intensity),
            f64::from(retained.intensity),
            float_rel,
            &format!("{at} intensity"),
        );
        close(
            f64::from(produced.quality),
            f64::from(retained.quality),
            float_rel,
            &format!("{at} quality"),
        );
        assert_eq!(produced.charge, retained.charge, "{at}: charge");
    }
}
