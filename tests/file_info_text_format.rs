#[test]
fn file_info_7_precision_15_statistics_match_the_retained_report() {
    let elements = || {
        FILE_INFO_7_CONSENSUS
            .iter()
            .flat_map(|(_, elements)| elements.iter())
    };
    let lines = range_lines(
        bounds(elements().map(|element| element.0)),
        bounds(elements().map(|element| element.1)),
        bounds(elements().map(|element| f64::from(element.2))),
        "intensity:      ",
    );
    for line in &lines {
        assert_eq!(occurrences(FILE_INFO_7_OUTPUT, line), 1, "{line}");
    }

    // FileInfo.cpp:2261-2328, including the pre-sized quality vector (five zeros).
    let mut intensities = Vec::new();
    let mut qualities = vec![0.0; FILE_INFO_7_CONSENSUS.len()];
    let (mut rt_delta, mut rt_abs, mut rt_avg) = (Vec::new(), Vec::new(), Vec::new());
    let (mut mz_delta, mut mz_abs, mut mz_avg) = (Vec::new(), Vec::new(), Vec::new());
    let (mut it_ratio, mut it_error, mut it_avg) = (Vec::new(), Vec::new(), Vec::new());
    for ((center_rt, center_mz, center_it, quality), members) in FILE_INFO_7_CONSENSUS {
        intensities.push(f64::from(center_it));
        qualities.push(f64::from(quality));
        let (mut rt_sum, mut mz_sum, mut it_sum) = (0.0, 0.0, 0.0);
        for (rt, mz, it) in members {
            let rt_diff: f64 = rt - center_rt;
            rt_delta.push(rt_diff);
            rt_abs.push(rt_diff.abs());
            rt_sum += rt_diff.abs();
            let mz_diff: f64 = mz - center_mz;
            mz_delta.push(mz_diff);
            mz_abs.push(mz_diff.abs());
            mz_sum += mz_diff.abs();
            let denominator = if center_it > 0.0 {
                f64::from(center_it)
            } else {
                1.0
            };
            let ratio = f64::from(it) / denominator;
            it_ratio.push(ratio);
            let error = if ratio < 1.0 { 1.0 / ratio } else { ratio };
            it_error.push(error);
            it_sum += error;
        }
        let size = members.len() as f64;
        rt_avg.push(rt_sum / size);
        mz_avg.push(mz_sum / size);
        it_avg.push(it_sum / size);
    }
    let (float_digits, double_digits) = (WRITTEN_DIGITS_F32, WRITTEN_DIGITS_F64);
    for block in [
        summary_block(
            "Intensities of consensus features:",
            intensities,
            float_digits,
        ),
        summary_block("Qualities of consensus features:", qualities, float_digits),
        summary_block(
            "Retention time differences (\"element - center\", weight 1 per element):",
            rt_delta,
            double_digits,
        ),
        summary_block(
            "Absolute retention time differences (\"|element - center|\", weight 1 per element):",
            rt_abs,
            double_digits,
        ),
        summary_block(
            "Average absolute differences of retention time within consensus features (\"|element - center|\", weight 1 per consensus features):",
            rt_avg,
            double_digits,
        ),
        summary_block(
            "Mass-to-charge differences (\"element - center\", weight 1 per element):",
            mz_delta,
            double_digits,
        ),
        summary_block(
            "Absolute differences of mass-to-charge (\"|element - center|\", weight 1 per element):",
            mz_abs,
            double_digits,
        ),
        summary_block(
            "Average absolute differences of mass-to-charge within consensus features (\"|element - center|\", weight 1 per consensus features):",
            mz_avg,
            double_digits,
        ),
        summary_block(
            "Intensity ratios (\"element / center\", weight 1 per element):",
            it_ratio,
            float_digits,
        ),
        summary_block(
            "Relative intensity error (\"max{(element / center), (center / element)}\", weight 1 per element):",
            it_error,
            float_digits,
        ),
        summary_block(
            "Average relative intensity error within consensus features (\"max{(element / center), (center / element)}\", weight 1 per consensus features):",
            it_avg,
            float_digits,
        ),
    ] {
        assert!(FILE_INFO_7_OUTPUT.contains(&block), "{block}");
    }
}

#[test]
fn file_info_9_peak_statistics_and_resolution_match_the_retained_report() {
    // Decoded from FileInfo_9_input.mzML: MS1 spectra 0 and 2 hold intensities
    // 15..1 (spectrum 3 is empty); the MS2 spectrum's "charge array" and
    // "signal to noise array" float arrays hold 20, 18, ..., 2.
    let ms1: Vec<f64> = (0..2).flat_map(|_| (1..=15).rev().map(f64::from)).collect();
    let meta: Vec<f64> = (1..=10).rev().map(|step| f64::from(2 * step)).collect();
    let p = WRITTEN_DIGITS_F32;
    for block in [
        summary_block("Intensities:", ms1, p),
        summary_block("Meta data: charge array", meta.clone(), p),
        summary_block("Meta data: signal to noise array", meta, p),
    ] {
        assert!(FILE_INFO_9_OUTPUT.contains(&block), "{block}");
    }
    // Both analyzers carry no resolution, which stays 0.0, at the default precision.
    let resolution = ostream_g(0.0, DEFAULT_STREAM_PRECISION);
    assert_eq!(
        occurrences(
            FILE_INFO_9_OUTPUT,
            &format!("  Mass Analyzer: Quadrupole ion trap (resolution: {resolution})")
        ),
        1
    );
}

