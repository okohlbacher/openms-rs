/// A normal `double` power of two: fraction bits zero, exponent bits neither all
/// zero nor all one.
fn is_power_of_two_f64(value: f64) -> bool {
    let bits = value.abs().to_bits();
    (bits >> 52) != 0 && (bits >> 52) != 0x7ff && (bits & ((1 << 52) - 1)) == 0
}

/// A normal `float` power of two.
fn is_power_of_two_f32(value: f32) -> bool {
    let bits = value.abs().to_bits();
    (bits >> 23) != 0 && (bits >> 23) != 0xff && (bits & ((1 << 23) - 1)) == 0
}

