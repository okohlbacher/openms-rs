/// Sign, significant digits without leading or trailing zeros, and decimal
/// exponent of a scientific text in either spelling (`1.5e15`, `1.5e+15`).
fn scientific_parts(text: &str) -> (bool, String, i32) {
    let negative = text.starts_with('-');
    let (mantissa, exponent) = text
        .trim_start_matches('-')
        .split_once('e')
        .expect("scientific text");
    let digits: String = mantissa.chars().filter(char::is_ascii_digit).collect();
    let digits = digits.trim_start_matches('0').trim_end_matches('0');
    let digits = if digits.is_empty() { "0" } else { digits };
    (
        negative,
        digits.to_owned(),
        exponent.parse().expect("decimal exponent"),
    )
}

