/// Residuals and the column-major Jacobian at every recorded vector.
fn check_functor(
    deviations: &mut Deviations,
    fixture: &Fixture,
    case: &str,
    traces: &MassTraces,
    weighted: bool,
) {
    let functor = GaussTraceFunctor::new(traces, weighted);
    assert_eq!(functor.inputs(), 3);
    let mut checked = 0;
    for label in [
        "x_init",
        "x_final_replica_500",
        "probe_true_10_680.1_1.5",
        "probe_negative_sigma",
        "probe_offset_8_679.5_2.0",
    ] {
        let prefix = format!("functor[{label}].");
        if !fixture.has(case, &format!("{prefix}x")) {
            continue;
        }
        checked += 1;
        let x = fixture.f64s(case, &format!("{prefix}x"));
        assert_eq!(
            usize::try_from(fixture.i64(case, &format!("{prefix}values"))).unwrap(),
            functor.values()
        );
        let mut fvec = vec![0.0; functor.values()];
        functor.residuals(&x, &mut fvec).unwrap();
        let context = format!("{case} {label}");
        deviations.check_all(
            "residuals",
            &context,
            &fvec,
            &fixture.f64s(case, &format!("{prefix}residuals")),
            EXACT_TOLERANCE,
        );
        let mut jac = DenseMatrix::zeros(functor.values(), 3);
        functor.jacobian(&x, &mut jac).unwrap();
        let expected = fixture.f64s(case, &format!("{prefix}jacobian_column_major"));
        let mut column_major = Vec::with_capacity(expected.len());
        for col in 0..3 {
            for row in 0..functor.values() {
                column_major.push(jac.at(row, col));
            }
        }
        deviations.check_all(
            "jacobian",
            &context,
            &column_major,
            &expected,
            EXACT_TOLERANCE,
        );
    }
    assert!(checked > 0, "{case}: no functor evaluation recorded");
}

/// The fit at 500 against the library fit, then every query the C2 driver
/// recorded, on the oracle's parameters.
fn check_fit500(
    deviations: &mut Deviations,
    fixture: &Fixture,
    case: &str,
    traces: &MassTraces,
    weighted: bool,
) {
    let f = |q: &str| fixture.f64(case, &format!("fit500.{q}"));
    let mut fitter = GaussTraceFitter::with_parameters(TraceFitterParams {
        max_iteration: 500,
        weighted,
    });
    fitter.fit(traces).unwrap();
    assert_eq!(
        fitter.parameters().max_iteration,
        fixture.i64(case, "fit500.member_max_iterations")
    );
    assert_eq!(
        fitter.parameters().weighted,
        fixture.boolean(case, "fit500.member_weighted")
    );
    deviations.check_all(
        "fit.params",
        case,
        &[fitter.height(), fitter.center(), fitter.sigma()],
        &[f("height"), f("center"), f("sigma")],
        FIT_TOLERANCE,
    );
    deviations.check(
        "fit.region_rt_span",
        case,
        fitter.region_rt_span(),
        f("region_rt_span"),
        EXACT_TOLERANCE,
    );

    let q = query_fitter(traces, weighted, [f("height"), f("center"), f("sigma")]);
    for (what, actual, expected) in [
        ("query.fwhm", q.fwhm(), f("fwhm")),
        ("query.area", q.area(), f("area")),
        (
            "query.lower_rt_bound",
            q.lower_rt_bound(),
            f("lower_rt_bound"),
        ),
        (
            "query.upper_rt_bound",
            q.upper_rt_bound(),
            f("upper_rt_bound"),
        ),
        ("query.value", q.value(q.center()), f("value_at_center")),
        (
            "query.value",
            q.value(q.center() + 1.0),
            f("value_at_center_plus_1"),
        ),
        (
            "query.value",
            q.value(q.center() - 2.0),
            f("value_at_center_minus_2"),
        ),
    ] {
        deviations.check(what, case, actual, expected, EXACT_TOLERANCE);
    }
    let class_max = f("arg_class_test_max_rt_span");
    let b = |name: &str| fixture.boolean(case, &format!("fit500.{name}"));
    for (what, actual, expected) in [
        (
            "query.check_maximal_rt_span",
            q.check_maximal_rt_span(class_max),
            b("check_maximal_rt_span_class_test"),
        ),
        (
            "query.check_maximal_rt_span",
            q.check_maximal_rt_span(class_max - 0.1),
            b("check_maximal_rt_span_class_test_minus_0_1"),
        ),
        (
            "query.check_maximal_rt_span",
            q.check_maximal_rt_span(f("arg_ffap_max_rt_span")),
            b("check_maximal_rt_span_ffap"),
        ),
        (
            "query.check_minimal_rt_span",
            q.check_minimal_rt_span((0.0, 4.0), 0.5),
            b("check_minimal_rt_span_0_4_0_5"),
        ),
        (
            "query.check_minimal_rt_span",
            q.check_minimal_rt_span((0.0, 4.0), 1.0),
            b("check_minimal_rt_span_0_4_1_0"),
        ),
        (
            "query.check_minimal_rt_span",
            q.check_minimal_rt_span(traces.rt_bounds().unwrap(), f("arg_ffap_min_rt_span")),
            b("check_minimal_rt_span_trace_bounds_ffap"),
        ),
    ] {
        deviations.expect_eq(what, case, actual, expected);
    }
    for (t, trace) in traces.iter().enumerate() {
        let expected = fixture.f64s(case, &format!("fit500.per_trace[{t}].compute_theoretical"));
        let actual: Vec<f64> = (0..trace.peaks.len())
            .map(|k| q.compute_theoretical(trace, k).unwrap())
            .collect();
        deviations.check_all(
            "query.compute_theoretical",
            case,
            &actual,
            &expected,
            EXACT_TOLERANCE,
        );
        let name = char::from(b'f' + u8::try_from(t).unwrap());
        let shift = 500.0 * f64::from(u32::try_from(t).unwrap());
        deviations.expect_eq(
            "query.gnuplot_formula",
            case,
            q.gnuplot_formula(trace, name, traces.baseline, shift)
                .as_str(),
            fixture.string(case, &format!("fit500.per_trace[{t}].gnuplot_formula")),
        );
    }
    deviations.expect_eq(
        "query.gnuplot_formula",
        case,
        q.gnuplot_formula(&traces[0], 'f', 0.0, 0.0).as_str(),
        fixture.string(case, "fit500.gnuplot_formula_f_0_0"),
    );
}

/// The budget sweep at the listed budgets: the library parameters (stored
/// where they change), the replica's status and, where recorded, `nfev` and
/// `njev`; and the boundary from which every result equals the result at the
/// largest budget.
fn check_sweep(
    deviations: &mut Deviations,
    fixture: &Fixture,
    case: &str,
    traces: &MassTraces,
    weighted: bool,
    budgets: &[i64],
) {
    let n_max = fixture.i64(case, "sweep.n_max");
    let statuses = fixture.i64s(case, "sweep.replica_status");
    let counts = fixture.has(case, "sweep.replica_nfev").then(|| {
        (
            fixture.i64s(case, "sweep.replica_nfev"),
            fixture.i64s(case, "sweep.replica_njev"),
        )
    });
    let mut library: Vec<(i64, Vec<f64>)> = Vec::new();
    for n in 1..=n_max {
        let quantity = format!("sweep.library[{n}]");
        if fixture.has(case, &quantity) {
            library.push((n, fixture.f64s(case, &quantity)));
        }
    }
    let reference = fit_at_budget(traces, weighted, n_max);
    let boundary = fixture.i64(case, "summary.smallest_identical_max_iteration_library");
    for &n in budgets {
        let context = format!("{case} max_iteration {n}");
        let fit = fit_at_budget(traces, weighted, n);
        let status = fit
            .status
            .as_ref()
            .unwrap_or_else(|e| panic!("{context}: {e}"));
        let index = usize::try_from(n - 1).unwrap();
        deviations.expect_eq(
            "sweep.status",
            &context,
            i64::from(status.code()),
            statuses[index],
        );
        if let Some((nfev, njev)) = &counts {
            deviations.expect_eq("sweep.nfev", &context, as_i64(fit.nfev), nfev[index]);
            deviations.expect_eq("sweep.njev", &context, as_i64(fit.njev), njev[index]);
        }
        deviations.check_all(
            "sweep.params",
            &context,
            &library_view(fit.x),
            library_at(&library, n),
            FIT_TOLERANCE,
        );
        let identical = fit.x.map(f64::to_bits) == reference.x.map(f64::to_bits);
        deviations.expect_eq("sweep.boundary", &context, identical, n >= boundary);
    }
}

fn as_i64(count: usize) -> i64 {
    i64::try_from(count).unwrap()
}

/// The library parameters at budget `n`: the last recorded change at or below
/// it.
fn library_at(library: &[(i64, Vec<f64>)], n: i64) -> &[f64] {
    &library
        .iter()
        .rev()
        .find(|(start, _)| *start <= n)
        .expect("the first budget is recorded")
        .1
}

