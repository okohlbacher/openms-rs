        let traces = fixture.traces(case);
        let mut start = GaussTraceFitter::new();
        start.set_initial_parameters(&traces).unwrap();
        check_start_values(&mut deviations, &fixture, case, &start);
        let mut fitter = GaussTraceFitter::new();
