//! `FEATUREFINDER/GaussTraceFitter` against its class test and the executed
//! product-SDK libOpenMS.
//!
//! Every `START_SECTION` of `GaussTraceFitter_test.cpp` (core bc9cc12) is
//! transcribed with its literals and its comparison macros. The file sets
//! `TOLERANCE_RELATIVE(1.001)` before the first section, so `TEST_REAL_SIMILAR`
//! is ClassTest's `isRealSimilar` with ratio 1.001 and the default absolute
//! tolerance 1e-5. The source test fits once before the sections and changes the
//! theoretical intensities inside the `fit` section; each test here rebuilds that
//! state in the same order.
//!
//! The oracle replays read `tests/data/gauss_trace_fitter/`, generated by
//! `../oracle/gauss-trace-fitter/run.sh` from the C2 class-level oracle
//! (`../oracle/featurefinder-picked`) and from its own driver. Library values
//! (start values, functor residuals and Jacobians, fitted parameters and every
//! query) are oracle-generated, tier 1; the Levenberg-Marquardt status, `nfev`,
//! `njev` and evaluation path come from C2's adapted `optimize_` replica, which
//! C2 checked against the library at every budget.
//!
//! Each fit is checked in two parts. The fitted parameters are compared within
//! 1e-9 relative, the work package's tolerance. The queries (bounds, FWHM, area,
//! values, span checks, `computeTheoretical`, gnuplot formulas) are then
//! evaluated on the oracle's own fitted parameters, so that they check the
//! query arithmetic and not the fit a second time, and are compared within
//! 1e-14 relative, as the start values, residuals and Jacobians are. Integers,
//! booleans, strings and the budget boundaries are compared exactly. The oracle
//! ran on macOS arm64 with Apple libm and Eigen 5.0.1; the port calls the
//! platform `exp` and `log` and the Eigen transcription in
//! `openms::math::fitters::levenberg_marquardt`. The platform `exp` differs in
//! the last bit between glibc and Apple libm, so the bit-identical counts and
//! some fit deviations differ between Linux and macOS; every tolerance holds on
//! both (`docs/TRACE_FITTER_SUPPORT.md`, native difference 1). Each replay
//! prints how many values were bit-identical and the largest relative
//! deviation it met.
//!
//! The fit, status, `nfev` and `njev` agreement of these replays holds for
//! these fixtures only. On other inputs the Eigen transcription departs from
//! the executed solver in the last bits, usually at the first trial step, and
//! fits can miss 1e-9 by orders of magnitude. The review probe's 79 inputs
//! (`tests/data/gauss_trace_fitter/solver_gap.tsv`, from
//! `../oracle/gauss-trace-fitter/solver-gap`) record that gap. Their start
//! values, and the residuals and Jacobians at them, are asserted; the ignored
//! `solver_gap_probe_reports_the_known_gap` prints the rest without asserting
//! any Rust value.
//!
//! That root cause was found and fixed in `src/math/fitters/levenberg_marquardt.rs`
//! by package B3b-LM-FIDELITY: the transcription summed left to right where
//! Eigen accumulates in SIMD lanes. What is left against these fixtures is the
//! platform split Eigen itself has - its arm64 kernels fuse their `pmadd` lanes
//! and its x86_64 `-mssse3` kernels do not - and the user decided on 2026-09-15
//! that the port matches the **Linux x86_64 Release** build on every target,
//! while these fixtures come from the macOS arm64 product SDK. See
//! `docs/DISTRIBUTION_FITTERS_SUPPORT.md` §1 and, for the asserted replay
//! against a Linux x86_64 Release trace of Eigen,
//! `tests/lm_eigen_path_differential.rs`.

