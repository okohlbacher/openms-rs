/// ClassTest `isRealSimilar` (ClassTest.cpp:364-470) with
/// `TOLERANCE_RELATIVE(1.001)` and the default `absdiff_max_allowed` 1e-5. The
/// source evaluates in `long double`; the transcribed cases are far from both
/// limits.
fn is_real_similar(number_1: f64, number_2: f64) -> bool {
    const ABSDIFF_MAX_ALLOWED: f64 = 1e-5;
    const RATIO_MAX_ALLOWED: f64 = 1.001;
    if number_1.is_nan() || number_2.is_nan() {
        return false;
    }
    let is_absdiff_small = (number_1 - number_2).abs() <= ABSDIFF_MAX_ALLOWED;
    if number_1 == 0.0 || number_2 == 0.0 {
        return (number_1 == 0.0 && number_2 == 0.0) || is_absdiff_small;
    }
    let mut ratio = number_1 / number_2;
    if ratio < 0.0 {
        return is_absdiff_small;
    }
    if ratio < 1.0 {
        ratio = 1.0 / ratio;
    }
    ratio <= RATIO_MAX_ALLOWED || is_absdiff_small
}

#[track_caller]
fn test_real_similar(actual: f64, expected: f64) {
    assert!(
        is_real_similar(actual, expected),
        "TEST_REAL_SIMILAR({actual}, {expected}) failed"
    );
}

