struct Fixture {
    rows: BTreeMap<(String, String), (String, String)>,
    cases: Vec<String>,
}

impl Fixture {
    fn parse(text: &str) -> Self {
        let mut rows = BTreeMap::new();
        let mut cases: Vec<String> = Vec::new();
        for line in text.lines() {
            let fields: Vec<&str> = line.splitn(4, '\t').collect();
            assert_eq!(fields.len(), 4, "malformed fixture row {line:?}");
            if !cases.iter().any(|case| case == fields[0]) {
                cases.push(fields[0].to_owned());
            }
            let previous = rows.insert(
                (fields[0].to_owned(), fields[1].to_owned()),
                (fields[2].to_owned(), fields[3].to_owned()),
            );
            assert!(previous.is_none(), "duplicate fixture row {line:?}");
        }
        Self { rows, cases }
    }

    /// Case names starting with `prefix`, in file order.
    fn cases(&self, prefix: &str) -> Vec<String> {
        self.cases
            .iter()
            .filter(|case| case.starts_with(prefix))
            .cloned()
            .collect()
    }

    fn has(&self, case: &str, quantity: &str) -> bool {
        self.rows
            .contains_key(&(case.to_owned(), quantity.to_owned()))
    }

    #[track_caller]
    fn raw(&self, case: &str, quantity: &str, kind: &str) -> &str {
        let (found, value) = self
            .rows
            .get(&(case.to_owned(), quantity.to_owned()))
            .unwrap_or_else(|| panic!("fixture has no row {case} {quantity}"));
        assert_eq!(found, kind, "{case} {quantity}");
        value
    }

    #[track_caller]
    fn f64(&self, case: &str, quantity: &str) -> f64 {
        bits64(self.raw(case, quantity, "f64"))
    }

    #[track_caller]
    fn f64s(&self, case: &str, quantity: &str) -> Vec<f64> {
        split(self.raw(case, quantity, "f64[]"))
            .map(bits64)
            .collect()
    }

    #[track_caller]
    fn f32s(&self, case: &str, quantity: &str) -> Vec<f32> {
        split(self.raw(case, quantity, "f32[]"))
            .map(|v| f32::from_bits(u32::from_str_radix(v, 16).unwrap()))
            .collect()
    }

    #[track_caller]
    fn i64(&self, case: &str, quantity: &str) -> i64 {
        self.raw(case, quantity, "i64").parse().unwrap()
    }

    #[track_caller]
    fn i64s(&self, case: &str, quantity: &str) -> Vec<i64> {
        split(self.raw(case, quantity, "i64[]"))
            .map(|v| v.parse().unwrap())
            .collect()
    }

    #[track_caller]
    fn boolean(&self, case: &str, quantity: &str) -> bool {
        match self.raw(case, quantity, "bool") {
            "true" => true,
            "false" => false,
            other => panic!("bad bool {other}"),
        }
    }

    #[track_caller]
    fn string(&self, case: &str, quantity: &str) -> &str {
        self.raw(case, quantity, "str")
    }

    /// The traces of `case`: m/z is not recorded and not read by the fitter.
    fn traces(&self, case: &str) -> MassTraces {
        let mut traces = MassTraces::new();
        let count = self.i64(case, "traces.size");
        for t in 0..count {
            let prefix = format!("trace[{t}].");
            let rts = self.f64s(case, &format!("{prefix}rt"));
            let intensities = self.f32s(case, &format!("{prefix}intensity"));
            assert_eq!(rts.len(), intensities.len());
            let mut trace = MassTrace {
                theoretical_int: self.f64(case, &format!("{prefix}theoretical_int")),
                ..MassTrace::default()
            };
            for (k, (&rt, &intensity)) in rts.iter().zip(&intensities).enumerate() {
                trace.peaks.push(TracePeak::new(0, k, rt, 0.0, intensity));
            }
            trace.update_maximum();
            traces.push(trace);
        }
        traces.baseline = self.f64(case, "traces.baseline");
        traces.max_trace = 0;
        traces
    }
}

fn split(value: &str) -> impl Iterator<Item = &str> {
    value.split(',').filter(|v| !v.is_empty())
}

fn bits64(value: &str) -> f64 {
    f64::from_bits(u64::from_str_radix(value, 16).unwrap())
}

/// Comparison against the oracle that also records the largest deviations,
/// printed at the end of each replay.
#[derive(Default)]
struct Deviations {
    compared: usize,
    bitwise: usize,
    max_relative: BTreeMap<&'static str, f64>,
}

impl Deviations {
    #[track_caller]
    fn check(
        &mut self,
        what: &'static str,
        context: &str,
        actual: f64,
        expected: f64,
        tolerance: f64,
    ) {
        self.compared += 1;
        if actual.to_bits() == expected.to_bits() || (actual.is_nan() && expected.is_nan()) {
            self.bitwise += 1;
            self.max_relative.entry(what).or_insert(0.0);
            return;
        }
        let scale = actual.abs().max(expected.abs());
        let relative = if actual == expected {
            0.0
        } else if scale.is_finite() && scale > 0.0 {
            (actual - expected).abs() / scale
        } else {
            f64::INFINITY
        };
        let slot = self.max_relative.entry(what).or_insert(0.0);
        if relative > *slot {
            *slot = relative;
        }
        assert!(
            relative <= tolerance,
            "{context} {what}: {actual:e} vs oracle {expected:e}, relative {relative:e} > {tolerance:e}"
        );
    }

    #[track_caller]
    fn check_all(
        &mut self,
        what: &'static str,
        context: &str,
        actual: &[f64],
        expected: &[f64],
        tolerance: f64,
    ) {
        assert_eq!(actual.len(), expected.len(), "{context} {what} length");
        for (index, (&a, &e)) in actual.iter().zip(expected).enumerate() {
            self.check(what, &format!("{context}[{index}]"), a, e, tolerance);
        }
    }

    #[track_caller]
    fn expect_eq<T: PartialEq + std::fmt::Debug>(
        &mut self,
        what: &'static str,
        context: &str,
        actual: T,
        expected: T,
    ) {
        assert!(
            actual == expected,
            "{context} {what}: {actual:?} vs oracle {expected:?}"
        );
    }

    fn report(&self, name: &str) {
        eprintln!(
            "{name}: {} values compared, {} bit-identical; largest relative deviation per quantity: {:?}",
            self.compared, self.bitwise, self.max_relative
        );
    }
}

