"""Generate the `test` and `minimum-rust` jobs of the Rust workflow.

Their feature slices used to be `--test` lists kept by hand: 183 names across
the two jobs, and 154 of the 332 integration tests on no reduced-feature line of
the minimum-Rust job at all. A test that exercises a feature-gated path without
carrying the gate's `#[cfg]` breaks only under a reduced feature set, and the
repository has shipped that twice (f2bf2ed, b1b52f7) - each time in a test some
slice happened to list.

So the minimum-Rust job's slices are derived. Every integration test runs there
under each smallest feature set its crate-level `#![cfg(...)]` admits - `{}` for
a test with no gate, which is a bare `cargo test --no-default-features` - and
that is exactly the build in which a missing `#[cfg]` shows. What cannot be
derived from a gate stays written down in JOBS: a slice that reaches an
item-level gate (`--features mzml --test peak_type_estimator`), a dependency
feature (`rusqlite/extra_check`), the serial/parallel split. Each such name
must be one the derivation would not add by itself, so everything listed below
is a choice somebody made.

The generated jobs stay in `.github/workflows/rust.yml` with every cargo line
written out, because `~/.local/bin/openms-ci-sweep.sh` reads the lines it runs
out of that file. Each job is split into matrix legs that run in parallel; a
leg is a set of steps, and the sweep, which ignores `if:`, still runs every
line of every leg. `tools/ci_coverage.py --check` refuses the result if any
recorded (job, features, target) unit stopped running.

  python3 tools/ci_matrix.py --check   # gate: the committed jobs are what this generates
  python3 tools/ci_matrix.py --write   # regenerate them in place
"""

