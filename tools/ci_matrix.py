class SpecError(Exception):
    pass


def feature_key(features):
    return " ".join(sorted(features.split())) or "{}"


def derived(table, tests):
    """feature key -> the tests that run there under their smallest gate-admitted set."""
    wanted = collections.defaultdict(set)
    for name in tests:
        for smallest in TestGates(name).minimal_feature_sets(table):
            wanted[" ".join(sorted(smallest)) or "{}"].add(name)
    return wanted


def resolve(job, table, tests):
    """The job's lines as (leg, command) in order, with a deriving job's tests added."""
    known = set(tests)
    keyed = {}
    for line in job.lines:
        if line.leg not in job.legs:
            raise SpecError(f"{job.name}: leg {line.leg!r} is not one of {job.legs}")
        if isinstance(line, (Bare, Slice)):
            key = (type(line).__name__, feature_key(line.features))
            if key in keyed:
                raise SpecError(f"{job.name}: two {key[0]} lines for features {key[1]}; merge them")
            keyed[key] = line
            unknown = set(getattr(line, "tests", ())) - known
            if unknown:
                raise SpecError(f"{job.name}: no integration test named {sorted(unknown)}")
    shadowed = sorted(k for kind, k in keyed if kind == "Slice" and ("Bare", k) in keyed)
    if shadowed:
        raise SpecError(f"{job.name}: a bare line already runs every test under {shadowed}; drop the slice")
    added = collections.defaultdict(set)
    extra = []
    if job.derive:
        for key, names in sorted(derived(table, tests).items()):
            if ("Bare", key) in keyed:
                continue
            line = keyed.get(("Slice", key))
            if line is None:
                spelling = "" if key == "{}" else key
                line = Slice(job.derived_leg, spelling)
                keyed[("Slice", key)] = line
                extra.append(line)
            redundant = sorted(set(line.tests) & names)
            if redundant:
                raise SpecError(
                    f"{job.name}: {redundant} under {key!r} would be derived anyway; "
                    "list only what a gate cannot say"
                )
            added[id(line)] |= names
    out = []
    for line in list(job.lines) + extra:
        if isinstance(line, Raw):
            out.append((line.leg, f"cargo test --locked {line.args}"))
            continue
        command = "cargo test --locked --no-default-features"
        if line.features:
            spelled = line.features if " " not in line.features else f'"{line.features}"'
            command += f" --features {spelled}"
        if isinstance(line, Slice):
            names = sorted(set(line.tests) | added[id(line)])
            if not names:
                raise SpecError(f"{job.name}: slice {line.features!r} selects no test")
            command += "".join(f" --test {name}" for name in names)
        out.append((line.leg, command))
    empty = [leg for leg in job.legs if not any(leg == l for l, _ in out)]
    if empty:
        raise SpecError(f"{job.name}: leg(s) {empty} run nothing")
    return out


def render_job(job, table, tests):
    lines = resolve(job, table, tests)
    legs = ", ".join(job.legs)
    text = [
        f"  {job.name}:\n",
        "    runs-on: ubuntu-latest\n",
        "    strategy:\n",
        "      fail-fast: false\n",
        "      matrix:\n",
        f"        leg: [{legs}]\n",
        "    steps:\n",
        "      - uses: actions/checkout@v4\n",
        f"      - uses: dtolnay/rust-toolchain@{job.toolchain}\n",
        "      - uses: Swatinem/rust-cache@v2\n",
        "        with:\n",
        "          key: ${{ matrix.leg }}\n",
        "      - uses: ./.github/actions/setup-libxml\n",
    ]
    for leg, command in lines:
        parse_cargo(command)  # refuse anything the coverage tool cannot read
        text.append(f"      - if: matrix.leg == '{leg}'\n")
        text.append(f"        run: {command}\n")
    return "".join(text)


def render(table=None, tests=None):
    table = cargo_features() if table is None else table
    tests = test_targets() if tests is None else tests
    return BEGIN + "".join(render_job(job, table, tests) for job in JOBS) + END


def split(workflow_text):
    if workflow_text.count(BEGIN) != 1 or workflow_text.count(END) != 1:
        raise SpecError("the workflow must hold exactly one generated block between the markers")
    head, rest = workflow_text.split(BEGIN)
    body, tail = rest.split(END)
    return head, BEGIN + body + END, tail


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--write", action="store_true")
    parser.add_argument("--workflow", default=str(WORKFLOW))
    args = parser.parse_args(argv)
    try:
        with open(args.workflow) as handle:
            current = handle.read()
        head, committed, tail = split(current)
        generated = render()
    except SpecError as problem:
        print(f"ci_matrix: {problem}")
        return 2
    if args.write:
        if committed != generated:
            with open(args.workflow, "w") as handle:
                handle.write(head + generated + tail)
            print("Regenerated the test and minimum-rust jobs.")
        else:
            print("The generated jobs are already current.")
        # A new test adds units to every line that selects all tests; record
        # them now, and refuse - loudly - anything this run would drop.
        status, message = record(args.workflow)
        print(message)
        return status
    if committed != generated:
        print("The test and minimum-rust jobs are not what tools/ci_matrix.py generates.")
        print("Edit JOBS in tools/ci_matrix.py, not the workflow, and run it with --write.")
        sys.stdout.writelines(difflib.unified_diff(
            committed.splitlines(True), generated.splitlines(True), "committed", "generated"))
        return 1
    print("The generated jobs are current.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
