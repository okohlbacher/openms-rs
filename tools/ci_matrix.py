BEGIN = "  # >>> generated by tools/ci_matrix.py from its JOBS - edit there, then run it with --write\n"
END = "  # <<< end of generated jobs\n"


class Raw:
    """A line written out whole: `cargo test --locked <args>`."""

    def __init__(self, leg, args):
        self.leg, self.args = leg, args


class Bare:
    """`cargo test --locked --no-default-features [--features F]`: every target cargo selects."""

    def __init__(self, leg, features=""):
        self.leg, self.features = leg, features


class Slice:
    """`--no-default-features [--features F]` over named tests; a deriving job adds its own."""

    def __init__(self, leg, features, tests=""):
        self.leg, self.features, self.tests = leg, features, tests.split()


class Job:
    def __init__(self, name, toolchain, legs, lines, derive=False, derived_leg=None):
        self.name, self.toolchain, self.legs, self.lines = name, toolchain, legs, lines
        self.derive, self.derived_leg = derive, derived_leg


