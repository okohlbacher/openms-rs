//! Checked experiment summaries and chromatogram organization. Only fields
//! consumed by each operation are inspected; unrelated metadata stay owned.

use super::{ChromatogramPeak, ExperimentRanges, MSExperiment, NumericRange, finite};
use crate::{Error, Result};
use std::{cmp::Ordering, mem::size_of};

/// Shared limits for one summary, TIC generation, sorting or array-clearing call.
/// Bytes bound cumulative temporary vectors and array-description payload
/// visited before destruction; ordinary borrowed peak inputs are not charged.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SummaryLimits {
    pub max_work: usize,
    pub max_bytes: usize,
    /// Cumulative raw TIC and resampled output points generated by one call.
    pub max_output_points: usize,
}
impl Default for SummaryLimits {
    fn default() -> Self {
        Self {
            max_work: 50_000_000,
            max_bytes: 256 * 1024 * 1024,
            max_output_points: 10_000_000,
        }
    }
}

impl MSExperiment {
    /// Recalculate TIC, optionally redistributing it onto an absolute RT grid.
    /// Nonpositive finite bin sizes preserve source scan order and duplicate RTs.
    /// Positive bins require nondecreasing selected RTs. Level zero includes all
    /// levels. Scan sums and every output update narrow to f32, as in the source.
    /// Unlike the existing unbinned `calculate_tic`, this API checks consumed
    /// values, numerical overflow and cumulative resources.
    pub fn calculate_tic_binned(
        &self,
        rt_bin_size: f32,
        ms_level: u32,
    ) -> Result<super::MSChromatogram> {
        self.calculate_tic_binned_with_limits(rt_bin_size, ms_level, SummaryLimits::default())
    }

    /// As [`Self::calculate_tic_binned`], with explicit resource ceilings.
    pub fn calculate_tic_binned_with_limits(
        &self,
        rt_bin_size: f32,
        ms_level: u32,
        limits: SummaryLimits,
    ) -> Result<super::MSChromatogram> {
        finite(f64::from(rt_bin_size), "TIC bin size")?;
        let mut work = Work::new(limits);
        work.consume(self.spectra.len())?;
        let selected = |level| ms_level == 0 || level == ms_level;
        let count = self.spectra.iter().filter(|s| selected(s.ms_level)).count();
        work.points(count)?;
        let mut peaks = work.vector::<ChromatogramPeak>(count)?;
        work.consume(self.spectra.len())?;
        for spectrum in &self.spectra {
            if !selected(spectrum.ms_level) {
                continue;
            }
            finite(spectrum.rt, "TIC retention time")?;
            work.consume(spectrum.peaks.len())?;
            let mut intensity = 0.0_f32;
            for peak in &spectrum.peaks {
                finite(f64::from(peak.intensity), "TIC intensity")?;
                intensity += peak.intensity;
                finite(f64::from(intensity), "TIC intensity sum")?;
            }
            peaks.push(ChromatogramPeak::new(spectrum.rt, intensity));
        }
        if rt_bin_size > 0.0 && !peaks.is_empty() {
            peaks = resample_tic(&peaks, f64::from(rt_bin_size), &mut work)?;
        }
        Ok(super::MSChromatogram::from_peaks(peaks))
    }

    /// Bounds of all stored chromatograms, including each Product m/z even if
    /// that chromatogram has no points. RT/intensity use actual points only.
    /// Results are computed on demand and do not require sorted input.
    pub fn chromatogram_ranges(&self) -> Result<ExperimentRanges> {
        self.chromatogram_ranges_with_limits(SummaryLimits::default())
    }
    /// As [`Self::chromatogram_ranges`], with explicit resource ceilings.
    pub fn chromatogram_ranges_with_limits(
        &self,
        limits: SummaryLimits,
    ) -> Result<ExperimentRanges> {
        self.chromatogram_ranges_inner(&mut Work::new(limits))
    }

    /// Combined RT, m/z and intensity bounds of all spectra and chromatograms.
    /// Includes empty-scan RT and empty-chromatogram Product m/z. Mobility is not
    /// represented by this three-dimensional result or the current containers.
    pub fn combined_ranges(&self) -> Result<ExperimentRanges> {
        self.combined_ranges_with_limits(SummaryLimits::default())
    }
    /// As [`Self::combined_ranges`], with explicit resource ceilings.
    pub fn combined_ranges_with_limits(&self, limits: SummaryLimits) -> Result<ExperimentRanges> {
        let mut work = Work::new(limits);
        let mut result = ExperimentRanges::default();
        work.consume(self.spectra.len())?;
        for spectrum in &self.spectra {
            extend(&mut result.rt, spectrum.rt, "spectrum retention time")?;
            work.consume(spectrum.peaks.len())?;
            for peak in &spectrum.peaks {
                extend(&mut result.mz, peak.mz, "spectrum m/z")?;
                extend(
                    &mut result.intensity,
                    f64::from(peak.intensity),
                    "spectrum intensity",
                )?;
            }
        }
        // Source combines spectrum ranges first, then chromatogram ranges.
        // Preserve the first equal endpoint, including the sign of zero.
        let chromatograms = self.chromatogram_ranges_inner(&mut work)?;
        for (target, source) in [
            (&mut result.rt, chromatograms.rt),
            (&mut result.mz, chromatograms.mz),
            (&mut result.intensity, chromatograms.intensity),
        ] {
            if let Some(source) = source {
                extend(target, source.min, "combined minimum")?;
                extend(target, source.max, "combined maximum")?;
            }
        }
        Ok(result)
    }

    fn chromatogram_ranges_inner(&self, work: &mut Work) -> Result<ExperimentRanges> {
        let mut result = ExperimentRanges::default();
        work.consume(self.chromatograms.len())?;
        for chromatogram in &self.chromatograms {
            extend(
                &mut result.mz,
                chromatogram.product.mz,
                "chromatogram product m/z",
            )?;
            work.consume(chromatogram.peaks.len())?;
            for peak in &chromatogram.peaks {
                extend(&mut result.rt, peak.rt, "chromatogram retention time")?;
                extend(
                    &mut result.intensity,
                    f64::from(peak.intensity),
                    "chromatogram intensity",
                )?;
            }
        }
        Ok(result)
    }

    /// Total number of spectrum peaks and chromatogram points, as source getSize.
    /// This differs from `len()`, which counts spectra.
    pub fn total_peak_count(&self) -> Result<u64> {
        self.total_peak_count_with_limits(SummaryLimits::default())
    }
    /// As [`Self::total_peak_count`], with explicit resource ceilings.
    pub fn total_peak_count_with_limits(&self, limits: SummaryLimits) -> Result<u64> {
        let mut work = Work::new(limits);
        work.consume(self.spectra.len())?;
        work.consume(self.chromatograms.len())?;
        self.spectra
            .iter()
            .map(|s| s.peaks.len())
            .chain(self.chromatograms.iter().map(|c| c.peaks.len()))
            .try_fold(0_u64, |sum, count| {
                sum.checked_add(u64::try_from(count).map_err(|_| invalid("peak count overflow"))?)
                    .ok_or_else(|| invalid("peak count overflow"))
            })
    }

    /// Exact source MS-level membership; zero is not a wildcard here.
    pub fn contains_scan_of_level(&self, ms_level: usize) -> Result<bool> {
        self.contains_scan_of_level_with_limits(ms_level, SummaryLimits::default())
    }
    /// As [`Self::contains_scan_of_level`], with explicit resource ceilings.
    pub fn contains_scan_of_level_with_limits(
        &self,
        ms_level: usize,
        limits: SummaryLimits,
    ) -> Result<bool> {
        let mut work = Work::new(limits);
        for spectrum in &self.spectra {
            work.consume(1)?;
            if u64::from(spectrum.ms_level) == ms_level as u64 {
                return Ok(true);
            }
        }
        Ok(false)
    }

    /// Whether any peak at exactly this level has intensity +0 or -0. Empty scans
    /// do not qualify. Finite nonzero signed intensities are accepted.
    pub fn has_zero_intensities(&self, ms_level: usize) -> Result<bool> {
        self.has_zero_intensities_with_limits(ms_level, SummaryLimits::default())
    }
    /// As [`Self::has_zero_intensities`], with explicit resource ceilings.
    pub fn has_zero_intensities_with_limits(
        &self,
        ms_level: usize,
        limits: SummaryLimits,
    ) -> Result<bool> {
        let mut work = Work::new(limits);
        for spectrum in &self.spectra {
            work.consume(1)?;
            if u64::from(spectrum.ms_level) != ms_level as u64 {
                continue;
            }
            for peak in &spectrum.peaks {
                work.consume(1)?;
                finite(f64::from(peak.intensity), "zero-intensity query")?;
                if peak.intensity == 0.0 {
                    return Ok(true);
                }
            }
        }
        Ok(false)
    }

    /// Stable Product-m/z ordering, optionally sorting each chromatogram's RTs
    /// and moving all nonempty annotation arrays with their points. Product-m/z
    /// ties retain input order, extending the source outer sort deterministically.
    /// RT ties preserve the source stable order.
    /// Preflight and permutation construction finish before any mutation.
    pub fn sort_chromatograms(&mut self, sort_rt: bool) -> Result<()> {
        self.sort_chromatograms_with_limits(sort_rt, SummaryLimits::default())
    }
    /// As [`Self::sort_chromatograms`], with explicit resource ceilings.
    pub fn sort_chromatograms_with_limits(
        &mut self,
        sort_rt: bool,
        limits: SummaryLimits,
    ) -> Result<()> {
        let mut work = Work::new(limits);
        work.consume(self.chromatograms.len())?;
        for chromatogram in &self.chromatograms {
            finite(chromatogram.product.mz, "chromatogram product m/z")?;
        }
        let mut outer = permutation(
            self.chromatograms.len(),
            |i| self.chromatograms[i].product.mz,
            &mut work,
        )?;
        let mut inner =
            work.vector::<Vec<usize>>(if sort_rt { self.chromatograms.len() } else { 0 })?;
        if sort_rt {
            work.consume(self.chromatograms.len())?;
            for chromatogram in &self.chromatograms {
                work.consume(chromatogram.peaks.len())?;
                for peak in &chromatogram.peaks {
                    finite(peak.rt, "chromatogram retention time")?;
                }
                let count = chromatogram.peaks.len();
                let arrays = add(
                    add(
                        chromatogram.float_data_arrays.len(),
                        chromatogram.integer_data_arrays.len(),
                    )?,
                    chromatogram.string_data_arrays.len(),
                )?;
                work.consume(arrays)?;
                for len in chromatogram
                    .float_data_arrays
                    .iter()
                    .map(|a| a.data.len())
                    .chain(
                        chromatogram
                            .integer_data_arrays
                            .iter()
                            .map(|a| a.data.len()),
                    )
                    .chain(chromatogram.string_data_arrays.iter().map(|a| a.data.len()))
                {
                    if len != 0 && len != count {
                        return Err(invalid("chromatogram annotation array length mismatch"));
                    }
                }
                // Each cycle uses fewer than count swaps; each swap visits every
                // array once, including empty arrays. No payload is cloned.
                work.consume(add(count, mul(count, add(arrays, 1)?)?)?)?;
                inner.push(permutation(count, |i| chromatogram.peaks[i].rt, &mut work)?);
            }
        }
        work.consume(mul(self.chromatograms.len(), 3)?)?;
        // Everything below is infallible and moves existing values only.
        for (chromatogram, order) in self.chromatograms.iter_mut().zip(&mut inner) {
            apply_permutation(order, |a, b| {
                chromatogram.peaks.swap(a, b);
                for array in &mut chromatogram.float_data_arrays {
                    if !array.data.is_empty() {
                        array.data.swap(a, b);
                    }
                }
                for array in &mut chromatogram.integer_data_arrays {
                    if !array.data.is_empty() {
                        array.data.swap(a, b);
                    }
                }
                for array in &mut chromatogram.string_data_arrays {
                    if !array.data.is_empty() {
                        array.data.swap(a, b);
                    }
                }
            });
        }
        apply_permutation(&mut outer, |a, b| self.chromatograms.swap(a, b));
        Ok(())
    }

    /// Remove all three annotation-array kinds from spectra only, returning
    /// whether any arrays (including empty arrays) were present. Chromatograms,
    /// peaks and ordinary/acquisition/identification metadata remain untouched.
    /// Destruction work is precharged before the first array is removed.
    pub fn clear_meta_data_arrays(&mut self) -> Result<bool> {
        self.clear_meta_data_arrays_with_limits(SummaryLimits::default())
    }
    /// As [`Self::clear_meta_data_arrays`], with explicit resource ceilings.
    pub fn clear_meta_data_arrays_with_limits(&mut self, limits: SummaryLimits) -> Result<bool> {
        let mut work = Work::new(limits);
        work.consume(self.spectra.len())?;
        let mut present = false;
        for spectrum in &self.spectra {
            spectrum.array_descriptions_with_budget(&mut work.remaining, &mut work.bytes)?;
            let arrays = add(
                add(
                    spectrum.float_data_arrays.len(),
                    spectrum.integer_data_arrays.len(),
                )?,
                spectrum.string_data_arrays.len(),
            )?;
            work.consume(mul(arrays, 2)?)?;
            present |= arrays != 0;
            for array in &spectrum.string_data_arrays {
                work.consume(array.data.len())?; // String destructor calls.
            }
        }
        work.consume(self.spectra.len())?;
        for spectrum in &mut self.spectra {
            spectrum.float_data_arrays = Vec::new();
            spectrum.integer_data_arrays = Vec::new();
            spectrum.string_data_arrays = Vec::new();
        }
        Ok(present)
    }
}

// A separate short loop is intentional: the existing general resampler uses a
// different algebraic expression. Keep source ceil(q+1), distance multiplication
// before division and per-update f32 narrowing, sharing this operation's budget.
fn resample_tic(
    input: &[ChromatogramPeak],
    spacing: f64,
    work: &mut Work,
) -> Result<Vec<ChromatogramPeak>> {
    work.consume(input.len())?;
    if input.windows(2).any(|p| p[0].rt > p[1].rt) {
        return Err(Error::UnsortedData);
    }
    let start = input[0].rt; // Caller excludes the empty case.
    let end = input[input.len() - 1].rt;
    let count = ((end - start) / spacing + 1.0).ceil();
    if !count.is_finite() || count < 1.0 || count > f64::from(i32::MAX) {
        return Err(invalid(
            "TIC grid size is not representable by the source index",
        ));
    }
    let count = count as usize;
    work.points(count)?;
    let mut output = work.vector::<ChromatogramPeak>(count)?;
    work.consume(count)?;
    let mut previous = None;
    for i in 0..count {
        let rt = start + i as f64 * spacing;
        finite(rt, "TIC grid retention time")?;
        if previous.is_some_and(|last| rt <= last) {
            return Err(invalid("TIC grid does not advance"));
        }
        output.push(ChromatogramPeak::new(rt, 0.0));
        previous = Some(rt);
    }
    let mut left = 0;
    for peak in input {
        work.consume(1)?;
        while left < output.len() && output[left].rt < peak.rt {
            work.consume(1)?;
            left += 1;
        }
        left = left.saturating_sub(1);
        if left + 1 == output.len() {
            output[left].intensity =
                checked_intensity(f64::from(output[left].intensity) + f64::from(peak.intensity))?;
            continue;
        }
        let dist_left = (peak.rt - output[left].rt).abs();
        let dist_right = (peak.rt - output[left + 1].rt).abs();
        let distance = dist_left + dist_right;
        if !distance.is_finite() || distance <= 0.0 {
            return Err(invalid(
                "TIC redistribution distance is not finite and positive",
            ));
        }
        output[left].intensity = checked_intensity(
            f64::from(output[left].intensity) + f64::from(peak.intensity) * dist_right / distance,
        )?;
        output[left + 1].intensity = checked_intensity(
            f64::from(output[left + 1].intensity)
                + f64::from(peak.intensity) * dist_left / distance,
        )?;
    }
    Ok(output)
}

fn checked_intensity(value: f64) -> Result<f32> {
    let narrowed = value as f32;
    finite(f64::from(narrowed), "TIC output intensity")?;
    Ok(narrowed)
}
fn extend(range: &mut Option<NumericRange>, value: f64, label: &str) -> Result<()> {
    finite(value, label)?;
    match range {
        Some(range) => {
            if value < range.min {
                range.min = value;
            }
            if value > range.max {
                range.max = value;
            }
        }
        None => {
            *range = Some(NumericRange {
                min: value,
                max: value,
            })
        }
    }
    Ok(())
}

// Return old-index -> destination-index. Bottom-up merging bounds actual work
// independently of the standard library's sorting implementation.
fn permutation(
    count: usize,
    coordinate: impl Fn(usize) -> f64,
    work: &mut Work,
) -> Result<Vec<usize>> {
    let mut order = work.vector::<usize>(count)?;
    let mut scratch = work.vector::<usize>(count)?;
    work.consume(mul(count, 2)?)?;
    order.extend(0..count);
    scratch.resize(count, 0);
    let mut width = 1;
    while width < count {
        work.consume(mul(count, 2)?)?;
        let mut begin = 0;
        while begin < count {
            let middle = begin.saturating_add(width).min(count);
            let end = middle.saturating_add(width).min(count);
            let (mut left, mut right) = (begin, middle);
            for slot in &mut scratch[begin..end] {
                if right == end
                    || (left < middle
                        && coordinate(order[left]).partial_cmp(&coordinate(order[right]))
                            != Some(Ordering::Greater))
                {
                    *slot = order[left];
                    left += 1;
                } else {
                    *slot = order[right];
                    right += 1;
                }
            }
            begin = end;
        }
        std::mem::swap(&mut order, &mut scratch);
        width = width.saturating_mul(2);
    }
    work.consume(count)?;
    for (destination, &original) in order.iter().enumerate() {
        scratch[original] = destination;
    }
    Ok(scratch)
}
fn apply_permutation(order: &mut [usize], mut swap: impl FnMut(usize, usize)) {
    for i in 0..order.len() {
        while order[i] != i {
            let other = order[i];
            swap(i, other);
            order.swap(i, other);
        }
    }
}

struct Work {
    remaining: usize,
    bytes: usize,
    points: usize,
}
impl Work {
    fn new(limits: SummaryLimits) -> Self {
        Self {
            remaining: limits.max_work,
            bytes: limits.max_bytes,
            points: limits.max_output_points,
        }
    }
    fn consume(&mut self, amount: usize) -> Result<()> {
        self.remaining = self
            .remaining
            .checked_sub(amount)
            .ok_or_else(|| invalid("experiment summary work limit exceeded"))?;
        Ok(())
    }
    fn points(&mut self, amount: usize) -> Result<()> {
        self.points = self
            .points
            .checked_sub(amount)
            .ok_or_else(|| invalid("experiment summary output limit exceeded"))?;
        Ok(())
    }
    fn vector<T>(&mut self, capacity: usize) -> Result<Vec<T>> {
        let bytes = if capacity == 0 {
            0
        } else {
            add(mul(capacity, size_of::<T>())?, 64)?
        };
        self.bytes = self
            .bytes
            .checked_sub(bytes)
            .ok_or_else(|| invalid("experiment summary allocation limit exceeded"))?;
        let mut result = Vec::new();
        result
            .try_reserve_exact(capacity)
            .map_err(|_| invalid("experiment summary allocation failed"))?;
        Ok(result)
    }
}
fn add(a: usize, b: usize) -> Result<usize> {
    a.checked_add(b)
        .ok_or_else(|| invalid("experiment summary size overflow"))
}
fn mul(a: usize, b: usize) -> Result<usize> {
    a.checked_mul(b)
        .ok_or_else(|| invalid("experiment summary size overflow"))
}
fn invalid(message: &str) -> Error {
    Error::InvalidValue(message.into())
}
